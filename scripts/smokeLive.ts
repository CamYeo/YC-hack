/** Bounded real-provider protocol check. Does not request TTS or inspect credential files. */
import { speakerNames } from "../shared/contracts"
import type { ClientMessage, CreateRoomResponse, ProviderStatus, ServerMessage } from "../shared/contracts"
import type { Contribution, PublicRoomState } from "../actor/src/roomTypes"

type Speech = Extract<ServerMessage, { type: "speak" }>
class SmokeFailure extends Error {}
function check(condition: unknown, message: string): asserts condition {
    if (!condition) throw new SmokeFailure(message)
}
const args = process.argv.slice(2)
if (args.includes("--help") || !args.includes("--text-only") || args.some(arg => arg !== "--text-only")) {
    process.stdout.write("Usage: ./node_modules/.bin/bun scripts/smokeLive.ts --text-only\nRuns against 127.0.0.1:3001. Requires real OpenAI, Agent Relay, and Terse.\nLogical playback acknowledgements only; no audio generation or audition. Maximum 120 seconds.\n")
    process.exit(args.includes("--help") ? 0 : 2)
}

const origin = "http://127.0.0.1:3001"
const startedAt = Date.now()
const deadline = startedAt + 117_000 // Leave three seconds to pause and close on failure.
const requestAbort = new AbortController()
const current: { state: PublicRoomState | null; providers: ProviderStatus | null } = { state: null, providers: null }
const speeches: Speech[] = []
let socket: WebSocket | null = null
let socketFailure: string | null = null
let cancelled = false
let closing = false
let minimumEpoch = 0
let completed = false
const hardLimit = setTimeout(() => {
    requestAbort.abort()
    if (socket?.readyState === WebSocket.OPEN) {
        socket.send(JSON.stringify({ type: "session.pause" } satisfies ClientMessage))
        socket.close()
    }
    process.stderr.write("Live smoke failed: 120-second limit reached; socket closed to pause the room.\n")
    process.exit(1)
}, 120_000)
const cancel = () => { cancelled = true; requestAbort.abort() }
process.on("SIGINT", cancel)
process.on("SIGTERM", cancel)

const report = (value: Record<string, unknown>) => process.stdout.write(`${JSON.stringify(value)}\n`)
function requireLive(providers: ProviderStatus) {
    check(providers.reasoning.mode === "live" && /OpenAI/i.test(providers.reasoning.label), "OpenAI must be live")
    check(providers.relay.mode === "live" && /Agent Relay/i.test(providers.relay.label) && providers.relay.deliveryMode !== "memory", "Agent Relay must use real delivery")
    check(providers.terse.mode === "live" && /Terse/i.test(providers.terse.label), "Terse must be live")
}
function realMessageId(value: string | null | undefined): value is string {
    return typeof value === "string" && value.length > 0 && !/^(?:fake|fixture|memory)[-_:]/i.test(value)
}
function send(message: ClientMessage) {
    check(socket?.readyState === WebSocket.OPEN, "Room connection is unavailable")
    socket.send(JSON.stringify(message))
}
async function waitFor<T>(read: () => T | null | undefined | false, label: string): Promise<T> {
    while (Date.now() < deadline) {
        check(!cancelled, "Cancelled")
        check(!socketFailure, socketFailure ?? "Room connection failed")
        const result = read()
        if (result !== null && result !== undefined && result !== false) return result
        await Bun.sleep(25)
    }
    throw new SmokeFailure(`Timed out waiting for ${label}`)
}
async function nextSpeech(): Promise<Speech> {
    const speech = await waitFor(() => speeches.find(item => item.generationEpoch >= minimumEpoch && current.state?.floor?.utteranceId === item.utteranceId), "the next AI contribution")
    speeches.splice(speeches.indexOf(speech), 1)
    return speech
}
async function acknowledgeSpeech(speech: Speech): Promise<Contribution> {
    const turnStarted = Date.now()
    const state = await waitFor(() => current.state?.floor?.utteranceId === speech.utteranceId && current.state, "Terse's floor lease")
    const proposal = state.pendingProposals.find(item => item.proposalId === state.floor?.proposalId)
    check(proposal?.reasoning === "openai", "The granted turn was not generated by OpenAI")
    check(realMessageId(proposal.relayMessageId), "The granted proposal has no real Relay message ID")
    check(speech.segments.length > 0, "The AI turn contains no segments")
    for (let index = 0; index < speech.segments.length; index++) {
        check(speech.generationEpoch >= minimumEpoch, "Speech was revoked before logical playback finished")
        send({ type: "playback.segment", utteranceId: speech.utteranceId, segmentIndex: index, event: "started" })
        send({ type: "playback.segment", utteranceId: speech.utteranceId, segmentIndex: index, event: "ended" })
        await waitFor(() => current.state?.contributions.find(item => item.id === speech.contributionId && item.segmentsHeard === index + 1), "the segment acknowledgement")
    }
    send({ type: "playback.finished", utteranceId: speech.utteranceId, outcome: "completed", error: null })
    const heard = await waitFor(() => current.state?.contributions.find(item => item.id === speech.contributionId && item.status === "heard" && realMessageId(item.relayMessageId)), "the heard contribution's Relay post")
    check(heard.heardText === speech.segments.join(" "), "Only an incomplete spoken prefix was committed")
    report({ speaker: speakerNames(current.state?.config?.theme)[heard.speakerId], heardText: heard.heardText, contributionId: heard.id, parentId: heard.replyToContributionId, relayMessageIds: { proposal: proposal.relayMessageId, heard: heard.relayMessageId }, timingMs: { sinceStart: Date.now() - startedAt, acknowledgement: Date.now() - turnStarted } })
    return heard
}

try {
    report({ playback: "Text-only protocol smoke: logical playback acknowledgements; no audio generated or auditioned" })
    const status = await fetch(`${origin}/api/status`, { signal: AbortSignal.any([requestAbort.signal, AbortSignal.timeout(10_000)]) })
    check(status.ok, "The backend status endpoint is unavailable")
    const providers = await status.json() as ProviderStatus
    requireLive(providers)
    report({ providers: { reasoning: providers.reasoning.label, relay: providers.relay.label, terse: providers.terse.label, voice: providers.voice.label } })
    const response = await fetch(`${origin}/api/rooms`, {
        method: "POST", headers: { "content-type": "application/json" },
        body: JSON.stringify({ topicId: "swe-retries", category: "software-engineering", format: "socratic", difficulty: "intermediate", participation: "participate", customQuestion: null, reading: null }),
        signal: AbortSignal.any([requestAbort.signal, AbortSignal.timeout(30_000)]),
    })
    check(response.status === 201, "Room creation failed")
    const room = await response.json() as CreateRoomResponse
    check(typeof room.roomId === "string" && typeof room.roomToken === "string", "Room creation returned an invalid response")
    // Neither this URL nor the response object is ever printed: both carry the room secret.
    const url = new URL("/ws", origin)
    url.protocol = "ws:"
    url.searchParams.set("roomId", room.roomId)
    url.searchParams.set("roomToken", room.roomToken)
    socket = new WebSocket(url)
    socket.addEventListener("error", () => { if (!closing) socketFailure = "Room socket failed" })
    socket.addEventListener("close", () => { if (!closing) socketFailure = "Room socket closed unexpectedly" })
    socket.addEventListener("message", event => {
        try {
            const message = JSON.parse(String(event.data)) as ServerMessage
            if (message.type === "snapshot") current.state = message.state
            else if (message.type === "welcome" || message.type === "providers") current.providers = message.providers
            else if (message.type === "speak") speeches.push(message)
            else if (message.type === "stop") minimumEpoch = Math.max(minimumEpoch, message.generationEpoch)
            else if (message.type === "notice" && message.level === "error") socketFailure = "The backend reported a room error"
        } catch { socketFailure = "The backend sent an invalid room message" }
    })
    await waitFor(() => socket?.readyState === WebSocket.OPEN, "the room connection")
    send({ type: "hello", clientId: `smoke-${crypto.randomUUID()}`, resume: false })
    const welcome = await waitFor(() => current.providers, "provider confirmation")
    requireLive(welcome)
    const opening: Contribution[] = []
    for (let turn = 0; turn < 3; turn++) opening.push(await acknowledgeSpeech(await nextSpeech()))
    check(new Set(opening.map(item => item.speakerId)).size === 3, "The opening did not include all three AI speakers")
    check(opening.slice(1).every(item => item.replyToContributionId !== null && opening.some(parent => parent.id === item.replyToContributionId && parent.createdAt <= item.createdAt)), "AI peers did not reference earlier contributions")
    const epoch = current.state?.generationEpoch ?? 0
    send({ type: "human.jumpIn", source: "button" })
    await waitFor(() => current.state && current.state.generationEpoch > epoch && !current.state.floor && current.state, "the human floor")
    const humanEventId = `smoke-human-${crypto.randomUUID()}`
    const humanText = "The timeout does not prove failure. Reuse the same idempotency key for the same purchase."
    send({ type: "human.contribution", eventId: humanEventId, text: humanText, inputMode: "text", replyToContributionId: opening.at(-1)?.id ?? null, addressedTo: "maya" })
    const human = await waitFor(() => current.state?.contributions.find(item => item.eventId === humanEventId && item.status === "human" && realMessageId(item.relayMessageId)), "the human's Relay post")
    report({ speaker: speakerNames(current.state?.config?.theme).human, heardText: human.heardText, contributionId: human.id, parentId: human.replyToContributionId, relayMessageId: human.relayMessageId, timingMs: Date.now() - startedAt })
    const reply = await acknowledgeSpeech(await nextSpeech())
    check(reply.replyToContributionId === human.id, "The next AI reply did not reference the actual human contribution")
    check(/timeout|idempoten|key|reus|purchase|dedup|retr(?:y|ie)|receipt/i.test(reply.heardText), "The AI reply did not engage with the human's timeout/key contribution")
    // Stop spontaneous turns while the explicit experiment goes through the evidence agent.
    const evidenceEpoch = current.state?.generationEpoch ?? 0
    send({ type: "human.jumpIn", source: "button" })
    await waitFor(() => current.state && current.state.generationEpoch > evidenceEpoch && !current.state.floor && current.state, "the experiment floor")
    const existingEvidence = new Set(current.state?.evidence.map(item => item.id) ?? [])
    send({ type: "evidence.request", toolId: "payment-retry-sim", caseId: "stable-key-retry" })
    const evidence = await waitFor(() => current.state?.evidence.find(item => !existingEvidence.has(item.id) && item.toolId === "payment-retry-sim" && item.caseId === "stable-key-retry" && item.status !== "pending"), "the stable-key evidence result")
    check(evidence.status === "returned" && evidence.result?.metrics.charges === 1, "The stable-key experiment did not return exactly one charge")
    check(realMessageId(evidence.resultRelayMessageId), "Evidence did not arrive through a real Relay message")
    report({ speaker: speakerNames(current.state?.config?.theme).evidence, evidenceCharges: evidence.result.metrics.charges, relayMessageId: evidence.resultRelayMessageId, timingMs: Date.now() - startedAt })
    send({ type: "session.end" })
    const ended = await waitFor(() => current.state?.phase === "ended" && current.state, "the end-of-session reflection")
    check(ended.reflection !== null, "The session ended without a reflection")
    check(ended.trace.some(item => item.channel === "terse" && item.kind === "floor.granted"), "No Terse floor grant was observed")
    completed = true
    report({ result: "PASS: three AI turns, a human-referenced reply, stable-key evidence, and ended session", timingMs: Date.now() - startedAt })
} catch (error) {
    // Never echo arbitrary network/server errors: they can include token-bearing URLs.
    process.stderr.write(`Live smoke failed: ${error instanceof SmokeFailure ? error.message : cancelled ? "Cancelled" : "Request or protocol failure"}.\n`)
    process.exitCode = 1
} finally {
    if (!completed && socket?.readyState === WebSocket.OPEN) {
        socket.send(JSON.stringify({ type: "session.pause" } satisfies ClientMessage))
        const cleanupDeadline = Math.min(startedAt + 119_500, Date.now() + 2_000)
        while (Date.now() < cleanupDeadline && current.state?.phase === "discussion") await Bun.sleep(25)
    }
    closing = true
    socket?.close(1000, "Smoke complete")
    requestAbort.abort()
    clearTimeout(hardLimit)
    process.off("SIGINT", cancel)
    process.off("SIGTERM", cancel)
}
